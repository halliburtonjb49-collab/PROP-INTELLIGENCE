create policy prop_chat_storage_insert on storage.objects
for insert to authenticated with check (
  bucket_id = 'prop-chat-private'
  and (storage.foldername(name))[1] = auth.uid()::text
  and lower(storage.extension(name)) in ('jpg', 'jpeg', 'png', 'webp')
);
create policy prop_chat_storage_read_own on storage.objects
for select to authenticated using (
  bucket_id = 'prop-chat-private'
  and (
    (storage.foldername(name))[1] = auth.uid()::text
    or exists (
      select 1 from public.prop_chat_messages m
      where m.attachment_path = name and m.deleted_at is null
    )
    or exists (
      select 1 from public.prop_chat_direct_messages d
      where d.attachment_path = name
        and d.deleted_at is null
        and public.is_prop_chat_conversation_member(d.conversation_id)
    )
  )
);
create policy prop_chat_storage_delete_own on storage.objects
for delete to authenticated using (
  bucket_id = 'prop-chat-private'
  and (storage.foldername(name))[1] = auth.uid()::text
);

