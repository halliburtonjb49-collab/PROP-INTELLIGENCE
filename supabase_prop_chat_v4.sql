values (
  'prop-chat-private',
  'prop-chat-private',
  false,
  5242880,
  array['image/jpeg', 'image/png', 'image/webp']
)
on conflict (id) do update
set public = false,
    file_size_limit = 5242880,
    allowed_mime_types = array['image/jpeg', 'image/png', 'image/webp'];

create table if not exists public.prop_chat_conversations (
  id uuid primary key default gen_random_uuid(),
  created_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.prop_chat_conversation_members (
  conversation_id uuid not null references public.prop_chat_conversations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  joined_at timestamptz not null default now(),
  last_read_at timestamptz not null default now(),
  primary key (conversation_id, user_id)
);

create table if not exists public.prop_chat_direct_messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.prop_chat_conversations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  username text not null,
  body text not null default '' check (char_length(body) <= 500),
  attachment_path text,
  attachment_kind text check (attachment_kind in ('image', 'ticket')),
  link_url text,
  created_at timestamptz not null default now(),
  edited_at timestamptz,
  deleted_at timestamptz,
  check (
    char_length(trim(body)) > 0
    or attachment_path is not null
  )
);

create table if not exists public.prop_chat_direct_reports (
  id bigint generated by default as identity primary key,
  message_id bigint references public.prop_chat_direct_messages(id) on delete set null,
  reporter_id uuid not null references auth.users(id) on delete cascade,
  message_user_id uuid,
  message_username text,
  message_body text,
  attachment_path text,
  reason text not null check (char_length(reason) between 3 and 200),
  status text not null default 'open'
    check (status in ('open', 'reviewed', 'resolved', 'dismissed')),
  created_at timestamptz not null default now(),
  unique(message_id, reporter_id)
);

alter table public.prop_chat_messages
  add column if not exists attachment_path text,
  add column if not exists attachment_kind text
    check (attachment_kind in ('image', 'ticket')),
  add column if not exists link_url text;

